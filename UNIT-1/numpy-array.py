from numpy import *;

a= array([1,2,3,4,5,6])
print(a)
a= array ([1.1,1.2,1.3,2.0])
print(a)
a= array(['a','b','c'])
print(a)
a=array(["Someone", "Someone1", "Someone2"])
print(a)

#arange
a = arange(1,6,2)
print(a)

#lnspace

a= linspace(1,20,5)
print(a)

#logspace

a= logspace(1,20,5)
print(a)

#zeros

a= zeros(20)

print(a)

#ones

a= ones(20)
print(a)